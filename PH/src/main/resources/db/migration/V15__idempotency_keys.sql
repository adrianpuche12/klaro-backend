-- V15 — Ventas idempotentes (propuesta "Ventas y stock sin carreras", 2026-11-03).
--
-- El POS manda un header Idempotency-Key (UUID por venta) en POST /shifts/{id}/sales.
-- Un reintento por red con la misma clave devuelve la venta ya registrada en vez de
-- cobrarla dos veces. La clave es única por empresa (tenant_id, idempotency_key).
--
-- TTL 24 h: una clave con created_at de hace más de 24 h se considera vencida y se
-- puede reutilizar (el backend la "reclama" con INSERT ... ON CONFLICT DO UPDATE ...
-- WHERE created_at < now() - 24 h). Las vencidas de la empresa se borran al registrar
-- una clave nueva, siempre con el rol de aplicación y bajo RLS: no hace falta ningún
-- proceso que vea datos de varias empresas.

CREATE TABLE idempotency_keys (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL,
    idempotency_key  VARCHAR(100) NOT NULL,
    -- Huella del pedido: la misma clave con otro contenido es un error del cliente (409).
    request_hash     VARCHAR(64)  NOT NULL,
    -- SET NULL: si la venta se cancela, un reintento con la misma clave sigue devolviendo
    -- la respuesta original (no vuelve a cobrar).
    sale_id          BIGINT       REFERENCES sales(id) ON DELETE SET NULL,
    -- Cuerpo JSON exacto que recibió el cliente la primera vez.
    response         TEXT,
    created_at       TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ux_idempotency_keys_tenant_key UNIQUE (tenant_id, idempotency_key)
);

CREATE INDEX idx_fk_idempotency_keys_sale_id ON idempotency_keys (sale_id);
CREATE INDEX idx_idempotency_keys_tenant_created ON idempotency_keys (tenant_id, created_at);

-- RLS igual que el resto de las tablas con tenant_id (V11).
ALTER TABLE idempotency_keys ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON idempotency_keys
    USING (tenant_id = app_current_tenant())
    WITH CHECK (tenant_id = app_current_tenant());

-- Grants explícitos al rol de aplicación (además de los DEFAULT PRIVILEGES de V11,
-- por si esta migración la corre un rol distinto del que los definió).
DO $$
DECLARE
    app_role text := current_database() || '_app';
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = app_role) THEN
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON idempotency_keys TO %I', app_role);
        EXECUTE format('GRANT USAGE, SELECT, UPDATE ON SEQUENCE idempotency_keys_id_seq TO %I', app_role);
    END IF;
END $$;
